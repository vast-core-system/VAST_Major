

// -----------------------------------------------------------------------------
// VTEAM memristor, digital model (Q16.16 state, w in [1 .. 65536] = [0 .. 1.0])
//
// Area-optimised version, now with the VTEAM parameters exposed.
// Bit-exact with the original model for the two programming voltages the system
// applies:
//
//   V_OFF port : applies the +0.30 V pulse  -> OFF-region parameters
//                (K_OFF, ALPHA_OFF, threshold V_TH_OFF = +0.20 V), state increases
//   V_ON  port : applies the -0.20 V pulse  -> ON-region parameters
//                (K_ON,  ALPHA_ON,  threshold V_TH_ON  = -0.15 V), state decreases
//
//   * f(V)  : K*((V/Vth - 1)^ALPHA) is evaluated ONCE at elaboration by the
//             constant function f_volt() below, with the same 32-bit arithmetic
//             as the original model.  With the default parameters it gives
//             F_UP = +327 and F_DOWN = -146.  No divider or multiplier in
//             hardware.
//   * f(w)  : Biolek window 1-(2w-1)^20 is stored as the threshold tables
//             dw_up()/dw_down() (45 / 21 entries), generated by running the
//             original arithmetic (incl. its 32-bit overflow behaviour near
//             w=0 and w=1) over every w.  No multiplier, no DSP.
//   * R(w)  : R_ON*w + R_OFF*(1-w) built from shift/add, combinational from
//             state_var.
//
// IMPORTANT: the dw tables were generated for F_UP = 327 and F_DOWN = -146.
// ALPHA_*, K_*, V_TH_* and V_*_PULSE are real parameters, but if you change
// them so that F_UP / F_DOWN change, the tables must be regenerated.  A
// simulation-only check below reports an error in that case.
// -----------------------------------------------------------------------------
module vteam_memristor #(
    // ---- VTEAM non-linearity exponents -------------------------------------
    parameter integer ALPHA_ON  = 2,
    parameter integer ALPHA_OFF = 2,

    // ---- VTEAM coefficients (Q16.16) ---------------------------------------
    parameter signed [31:0] K_ON  = -32'sd1311,    // -0.02
    parameter signed [31:0] K_OFF =  32'sd1311,    // +0.02

    // ---- switching thresholds (Q16.16) -------------------------------------
    parameter signed [31:0] V_TH_ON  = -32'sd9830,   // -0.15 V
    parameter signed [31:0] V_TH_OFF =  32'sd13107,  // +0.20 V

    // ---- programming pulse levels applied by the V_ON / V_OFF ports --------
    parameter signed [31:0] V_ON_PULSE  = -32'sd13107,  // -0.20 V
    parameter signed [31:0] V_OFF_PULSE =  32'sd19661,  // +0.30 V

    // ---- state ---------------------------------------------------------------
    parameter logic [16:0] W_INIT = 17'd6554,    // 0.1
    parameter logic [16:0] W_MIN  = 17'd1,
    parameter logic [16:0] W_MAX  = 17'd65536    // 1.0
)(
    input  logic        clk,
    input  logic        rst,          // asynchronous, active high
    input  logic        V_OFF,        // apply +0.30 V pulse (state increases); wins over V_ON
    input  logic        V_ON,         // apply -0.20 V pulse (state decreases)
    (* retiming_forward = 1 *)
    output logic [16:0] state_var,    // Q16.16 state
    output logic [13:0] resistance    // Ohm, R_ON=100 .. R_OFF=16000
);

    // ---- f(V) = K * ((V/Vth - 1)^ALPHA), evaluated at elaboration ------------
    // Same operation order and 32-bit signed arithmetic as the original model:
    //   (K * ((((V <<< 16) / Vth) - 65536) ** ALPHA >>> 16)) >>> 16
    function automatic integer f_volt(input integer v,
                                      input integer vth,
                                      input integer k,
                                      input integer alpha);
        integer q, p, n;
        begin
            q = ((v <<< 16) / vth) - 65536;
            p = 1;
            for (n = 0; n < alpha; n = n + 1) p = p * q;
            f_volt = (k * (p >>> 16)) >>> 16;
        end
    endfunction

    localparam integer F_UP   = f_volt(V_OFF_PULSE, V_TH_OFF, K_OFF, ALPHA_OFF);  // +327
    localparam integer F_DOWN = f_volt(V_ON_PULSE,  V_TH_ON,  K_ON,  ALPHA_ON);   // -146

    // simulation-only sanity check (ignored by synthesis)
    // synthesis translate_off
    initial begin
        if (F_UP !== 327 || F_DOWN !== -146)
            $error("vteam_memristor: dw tables were generated for F_UP=327 / F_DOWN=-146 but the parameters give %0d / %0d. Regenerate dw_up()/dw_down().",
                   F_UP, F_DOWN);
        if (!(V_OFF_PULSE >= V_TH_OFF) || !(V_ON_PULSE <= V_TH_ON))
            $error("vteam_memristor: pulse levels must lie beyond the thresholds (V_OFF_PULSE >= V_TH_OFF, V_ON_PULSE <= V_TH_ON).");
    end
    // synthesis translate_on

    // ---- dw per pulse as a function of the current state --------------------
    function automatic logic signed [9:0] dw_up(input logic [16:0] s);
        logic signed [9:0] r;
        if (s >= 17'd62590) r = 327; //0.1
        else if (s >= 17'd62069) r = 328; //0.9470
        else if (s >= 17'd61712) r = 329; //0.9416
        else if (s >= 17'd61433) r = 330; //0.93739
        else if (s >= 17'd61198) r = 331; //0.9338
        else if (s >= 17'd60994) r = 332; //0.9306
        else if (s >= 17'd60813) r = 333; //0.9279
        else if (s >= 17'd60647) r = 334; //0.9253
        else if (s >= 17'd60495) r = 335; //0.9230
        else if (s >= 17'd60353) r = 336; //0.9209
        else if (s >= 17'd60323) r = 337; //0.9204
        else if (s >= 17'd60294) r = 316; //0.9200
        else if (s >= 17'd60149) r = 317; //0.9178
        else if (s >= 17'd59989) r = 318; //0.9153
        else if (s >= 17'd59807) r = 319; //0.9125
        else if (s >= 17'd59600) r = 320; //0.9094
        else if (s >= 17'd59357) r = 321; //0.9057
        else if (s >= 17'd59062) r = 322; //0.9012
        else if (s >= 17'd58687) r = 323; //0.8954
        else if (s >= 17'd58167) r = 324; //0.8875
        else if (s >= 17'd57305) r = 325; //0.8744
        else if (s >= 17'd51687) r = 326; //0.7886
        else if (s >= 17'd13850) r = 327; //0.2113
        else if (s >= 17'd8232 ) r = 326; //0.1256
        else if (s >= 17'd7370 ) r = 325; //0.1124
        else if (s >= 17'd6850 ) r = 324; //0.1045
        else if (s >= 17'd6475 ) r = 323; //0.0988
        else if (s >= 17'd6180 ) r = 322; //0.0942
        else if (s >= 17'd5937 ) r = 321; //0.0905
        else if (s >= 17'd5730 ) r = 320; //0.0874
        else if (s >= 17'd5548 ) r = 319; //0.0846
        else if (s >= 17'd5388 ) r = 318; //0.0822
        else if (s >= 17'd5243 ) r = 317; //0.0800
        else if (s >= 17'd5214 ) r = 316; //0.0795
        else if (s >= 17'd5184 ) r = 337; //0.0791
        else if (s >= 17'd5042 ) r = 336; //0.0769
        else if (s >= 17'd4890 ) r = 335; //0.0746
        else if (s >= 17'd4724 ) r = 334; //0.0720
        else if (s >= 17'd4543 ) r = 333; //0.0693
        else if (s >= 17'd4339 ) r = 332; //0.0662
        else if (s >= 17'd4104 ) r = 331; //0.0626
        else if (s >= 17'd3825 ) r = 330; //0.0583
        else if (s >= 17'd3468 ) r = 329; //0.0529
        else if (s >= 17'd2947 ) r = 328; //0.0449
        else                  r = 327;
        return r;
    endfunction

    function automatic logic signed [9:0] dw_down(input logic [16:0] s);
        logic signed [9:0] r;
        if (s >= 17'd65012) r = -146;  //0.992
        else if (s >= 17'd61974) r = -147; //0.945
        else if (s >= 17'd61317) r = -148; //0.9356
        else if (s >= 17'd60862) r = -149; //0.9286
        else if (s >= 17'd60501) r = -150; //0.9231
        else if (s >= 17'd60323) r = -151; //0.9204
        else if (s >= 17'd60143) r = -142; //0.9177
        else if (s >= 17'd59753) r = -143; //0.9117
        else if (s >= 17'd59211) r = -144; //0.9034
        else if (s >= 17'd58311) r = -145; //0.8897
        else if (s >= 17'd7226 ) r = -146; //0.1102
        else if (s >= 17'd6326 ) r = -145; //0.0965
        else if (s >= 17'd5784 ) r = -144; //0.0882
        else if (s >= 17'd5394 ) r = -143; //0.0823
        else if (s >= 17'd5214 ) r = -142; //0.0795
        else if (s >= 17'd5036 ) r = -151; //0.0768
        else if (s >= 17'd4675 ) r = -150; //0.0713
        else if (s >= 17'd4220 ) r = -149; //0.0643
        else if (s >= 17'd3563 ) r = -148; //0.0543
        else if (s >= 17'd525  ) r = -147; //0.0080
        else                  r = -146;
        return r;
    endfunction

    // ---- state update --------------------------------------------------------
    logic signed [9:0]  dw;
    logic signed [17:0] w_next;

    always_comb begin
        if      (V_OFF) dw = dw_up(state_var);
        else if (V_ON)  dw = dw_down(state_var);
        else            dw = 10'sd0;
        w_next = $signed({1'b0, state_var}) + dw;
    end

    always_ff @(posedge clk or posedge rst) begin
        if (rst)                                     state_var <= W_INIT;
        else if (w_next < $signed({1'b0, W_MIN}))    state_var <= W_MIN;
        else if (w_next > $signed({1'b0, W_MAX}))    state_var <= W_MAX;
        else                                         state_var <= w_next[16:0];
    end

    // ---- resistance: R = R_ON*w + R_OFF*(1-w), R_ON=100, R_OFF=16000 --------
    // 100*w     = (w<<6)+(w<<5)+(w<<2)
    // 16000*x   = (x<<14)-(x<<8)-(x<<7)
    logic [16:0] w_inv;
    logic [22:0] r_on_part;
    logic [29:0] r_off_part;

    always_comb begin
        w_inv      = 17'd65536 - state_var;
        r_on_part  = ({6'd0, state_var} << 6) + ({6'd0, state_var} << 5) + ({6'd0, state_var} << 2);
        r_off_part = ({13'd0, w_inv} << 14) - ({13'd0, w_inv} << 8) - ({13'd0, w_inv} << 7);
        resistance = 14'(r_on_part[22:16]) + 14'(r_off_part[29:16]);
    end
    
    

endmodule